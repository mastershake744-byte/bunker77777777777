/** Товар (котел) */
export interface Product {
  id: number;
  /** Уникальный идентификатор для URL — используется в /product/[url]/ */
  url: string;
  name: string;
  /** Путь к изображению товара */
  photo: string;
  /** Скриншоты/фото от пользователей */
  screenshot?: string[];
  tags?: string[];
  price: string;
  document: string;
  /** Раздел каталога: "Пеллетные котлы" или "Твердотопливные котлы" */
  razdel: string;
  availability: string;
  sklad: string;
  pdfName?: string;
  documents?: string;
  characteristics: {
    power: string;
    waterVolume: string;
    chimneyDiameter: string;
    weight: string;
    bunkerVolume: string;
    waterConsumptionNominal: string;
    waterConsumptionMin: string;
    chimneyHeight: string;
    pipeDiameter: string;
    workingTemperature: string;
    maxTemperature: string;
    valvePressure: string;
    flueGasTemperature: string;
    fuelConsumptionMax: string;
    fuelConsumptionNominal: string;
  };
  /** Габаритные размеры */
  razmer: { width: string; height: string; depth: string; unit: string };
}

/** Категория товаров */
export interface Category {
  id: number;
  url: string;
  name: string;
  text: string;
  seo_title: string;
  seo_description: string;
  bread: string;
  /** ID товаров, входящих в категорию */
  products: number[];
}

