export const categories = _categories;

/** Найти товар по url (используется в /product/[url]/page.tsx) */
export function getBoilerByUrl(url: string): Product | undefined {
  return boilersData.find((b) => b.url === url || b.url === url + '/');
}

/** Найти категорию по url (используется в /category/[url]/page.tsx) */
export function getCategoryByUrl(url: string): Category | undefined {
  return categories.find((c) => c.url === url);
}

/** Вернуть массив товаров по ID категории */
export function getProductsByCategoryId(id: number): Product[] {
  const cat = categories.find((c) => c.id === id);
  if (!cat) return [];
  return cat.products.map((pid) => boilersData.find((b) => b.id === pid)).filter(Boolean) as Product[];
}
